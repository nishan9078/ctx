export const schema = `
PRAGMA busy_timeout=5000;
PRAGMA journal_mode=WAL;
PRAGMA synchronous=FULL;
PRAGMA foreign_keys=ON;
CREATE TABLE IF NOT EXISTS tasks (id TEXT PRIMARY KEY, status TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS plans (task_id TEXT NOT NULL REFERENCES tasks(id), version INTEGER NOT NULL, data TEXT NOT NULL, PRIMARY KEY(task_id, version));
CREATE TABLE IF NOT EXISTS steps (task_id TEXT NOT NULL REFERENCES tasks(id), id TEXT NOT NULL, status TEXT NOT NULL, data TEXT NOT NULL, PRIMARY KEY(task_id,id));
CREATE TABLE IF NOT EXISTS attempts (id TEXT PRIMARY KEY, task_id TEXT NOT NULL REFERENCES tasks(id), step_id TEXT NOT NULL, idempotency_key TEXT NOT NULL UNIQUE, status TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS events (sequence INTEGER PRIMARY KEY AUTOINCREMENT, task_id TEXT NOT NULL REFERENCES tasks(id), timestamp TEXT NOT NULL, type TEXT NOT NULL, data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS leases (task_id TEXT PRIMARY KEY REFERENCES tasks(id), owner TEXT NOT NULL, pid INTEGER NOT NULL, host TEXT NOT NULL, expires_at INTEGER NOT NULL);
CREATE TABLE IF NOT EXISTS checkpoints (id INTEGER PRIMARY KEY AUTOINCREMENT, task_id TEXT NOT NULL REFERENCES tasks(id), event_sequence INTEGER NOT NULL REFERENCES events(sequence), data TEXT NOT NULL);
CREATE TABLE IF NOT EXISTS resources (task_id TEXT NOT NULL REFERENCES tasks(id), path TEXT NOT NULL, kind TEXT NOT NULL, PRIMARY KEY(task_id,path));
CREATE TABLE IF NOT EXISTS artifacts (task_id TEXT NOT NULL REFERENCES tasks(id), path TEXT NOT NULL, checksum TEXT NOT NULL, kind TEXT NOT NULL, PRIMARY KEY(task_id,path));

`;
